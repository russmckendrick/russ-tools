/**
 * WCAG 2.x contrast for every measured pair in palettes.mjs, plus an OKLab
 * distance between the accent and each status hue (how easily the two are
 * told apart). Run: node _work/contrast.mjs  (add --write to emit contrast.md
 * and contrast.json beside the proposal).
 */
import { writeFileSync } from 'node:fs';
import { PALETTES, DATASHEET, THEME_PAIRS, BAND_PAIRS } from './palettes.mjs';
import { markColours } from './marks.mjs';

const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
const lin = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
export const luminance = (hex) => {
  const [r, g, b] = rgb(hex).map(lin);
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
export const contrast = (a, b) => {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};

const oklab = (hex) => {
  const [r, g, b] = rgb(hex).map(lin);
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
  return [
    0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s,
    1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s,
    0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s,
  ];
};
export const deltaE = (a, b) => {
  const [x, y] = [oklab(a), oklab(b)];
  return Math.hypot(x[0] - y[0], x[1] - y[1], x[2] - y[2]);
};
export const hue = (hex) => {
  const [, a, b] = oklab(hex);
  return (Math.atan2(b, a) * 180) / Math.PI + (b < 0 ? 360 : 0);
};

/** Every measurement for one palette, as plain rows. */
export function measure(p) {
  const rows = [];
  for (const theme of ['light', 'dark']) {
    for (const [fg, bg, floor, what] of THEME_PAIRS) {
      const ratio = contrast(p[theme][fg], p[theme][bg]);
      rows.push({ theme, fg, bg, fgHex: p[theme][fg], bgHex: p[theme][bg], floor, what, ratio, pass: ratio >= floor });
    }
  }
  for (const [fg, bg, floor, what] of BAND_PAIRS) {
    const ratio = contrast(p.band[fg], p.band[bg]);
    rows.push({ theme: 'band', fg, bg, fgHex: p.band[fg], bgHex: p.band[bg], floor, what, ratio, pass: ratio >= floor });
  }
  return rows;
}

/** How far the accent sits from each status hue, per theme. Under 0.10 is hard to tell apart at a glance. */
export function separation(p) {
  const out = [];
  for (const theme of ['light', 'dark']) {
    for (const s of ['success', 'warning', 'error', 'info']) {
      out.push({ theme, status: s, dE: deltaE(p[theme]['primary-text'], p[theme][s]) });
    }
  }
  return out;
}

/** The mark's two inks against the two grounds it is drawn on. A graphic object: 3:1. */
export function measureMark(id, p) {
  const c = markColours(id, p);
  const rows = [];
  for (const [ground, bg, set] of [['paper', p.light.surface, c.light], ['dark page', p.dark.surface, c.dark], ['band', p.band.band, c.dark]]) {
    for (const part of ['ink', 'lit']) {
      const ratio = contrast(set[part], bg);
      rows.push({ ground, part, fgHex: set[part], bgHex: bg, ratio, floor: 3, pass: ratio >= 3 });
    }
  }
  return rows;
}

const fmt = (n) => n.toFixed(2);

if (import.meta.url === `file://${process.argv[1]}`) {
  const all = { ...PALETTES, datasheet: DATASHEET };
  let md = '# Contrast report\n\nGenerated by `_work/contrast.mjs` from `_work/palettes.mjs`. WCAG 2.x relative-luminance ratios.\nFloors: 4.5 for body text, 3 for large text, graphic objects and control boundaries.\n';
  const json = {};
  let failures = 0;
  for (const [id, p] of Object.entries(all)) {
    const rows = measure(p);
    json[id] = rows.map((r) => ({ ...r, ratio: Number(r.ratio.toFixed(2)) }));
    const bad = rows.filter((r) => !r.pass);
    if (id !== 'datasheet') failures += bad.length;
    const min = (t) => Math.min(...rows.filter((r) => r.theme === t && r.floor === 4.5).map((r) => r.ratio));
    console.log(
      `${p.name.padEnd(20)} ${rows.length} pairs, ${bad.length} below floor · lowest text pair: light ${fmt(min('light'))} dark ${fmt(min('dark'))} band ${fmt(min('band'))}`
    );
    for (const r of bad) console.log(`   FAIL ${r.theme} ${r.fg} on ${r.bg}: ${fmt(r.ratio)} < ${r.floor} (${r.fgHex} on ${r.bgHex})`);
    md += `\n## ${p.name} — ${p.scheme}\n\n${rows.length} pairs measured, ${bad.length} below floor.\n`;
    for (const theme of ['light', 'dark', 'band']) {
      md += `\n### ${theme === 'band' ? 'On the band (both themes)' : theme[0].toUpperCase() + theme.slice(1)}\n\n| Foreground | Ground | Ratio | Floor | | Use |\n|---|---|---:|---:|---|---|\n`;
      for (const r of rows.filter((x) => x.theme === theme)) {
        md += `| \`${r.fg}\` ${r.fgHex} | \`${r.bg}\` ${r.bgHex} | ${fmt(r.ratio)} | ${r.floor} | ${r.pass ? 'pass' : '**FAIL**'} | ${r.what} |\n`;
      }
    }
    md += `\n### Accent against status hues (OKLab distance; under 0.10 is hard to tell apart)\n\n| Theme | success | warning | error | info |\n|---|---:|---:|---:|---:|\n`;
    const sep = separation(p);
    for (const theme of ['light', 'dark']) {
      md += `| ${theme} | ${sep.filter((s) => s.theme === theme).map((s) => fmt(s.dE)).join(' | ')} |\n`;
    }
    if (id !== 'datasheet') {
      const marks = measureMark(id, p);
      failures += marks.filter((m) => !m.pass).length;
      md += `\n### The mark (graphic object, floor 3)\n\n| Part | Ground | Ratio | |\n|---|---|---:|---|\n`;
      for (const m of marks) md += `| ${m.part} ${m.fgHex} | ${m.ground} ${m.bgHex} | ${fmt(m.ratio)} | ${m.pass ? 'pass' : '**FAIL**'} |\n`;
      console.log('   mark  ' + marks.map((m) => `${m.part}/${m.ground} ${fmt(m.ratio)}${m.pass ? '' : ' FAIL'}`).join('  '));
    }
    console.log('   accent vs status dE  ' + sep.map((s) => `${s.theme[0]}:${s.status.slice(0, 4)} ${fmt(s.dE)}`).join('  '));
    console.log(`   band vs dark page ${fmt(contrast(p.band.band, p.dark.surface))} · band vs light page ${fmt(contrast(p.band.band, p.light.surface))} · primary hue ${hue(p.dark['primary-text']).toFixed(0)}`);
  }
  if (process.argv.includes('--write')) {
    const dir = new URL('../', import.meta.url).pathname;
    writeFileSync(dir + 'contrast.md', md);
    writeFileSync(dir + '_work/contrast.json', JSON.stringify(json, null, 1));
    console.log('wrote contrast.md');
  }
  process.exitCode = failures ? 1 : 0;
}
